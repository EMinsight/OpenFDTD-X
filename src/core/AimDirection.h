// AimDirection.h — 音源の「向き」文字列を単位ベクトルへ解く。
//
// AcousticSourceRow::aim は利用者が自由に書く文字列で、既定値は
// "+X" / "-Z" / "-Z 30°" のような形。3D シーンに法線矢印を描くには
// これをベクトルにする必要がある。
//
// 受け付ける書式:
//   ① 軸トークン        "+X" / "-X" / "+Y" / "-Y" / "+Z" / "-Z"
//                       (符号なし "X" は "+X" とみなす)
//   ② 軸トークン + 角度  "+X 30" / "-Z 30°" / "+Y 15deg"
//                       角度は **その軸から下向き (−Z) へ傾ける量**。
//                       軸が ±Z のときは下向きが定義できないので +X へ傾ける
//                       (任意だが一意な基準。ここで決め打ちしないと
//                        "-Z 30°" のような既定値が解けない)。
//   ③ 明示ベクトル      "0,0,-1" / "1 0 0" / "0.5, 0, -0.5"
//
// 解けない文字列は false を返す。**推測で適当な向きを描かない** —
// 向きが分からないものに矢印を出すと、間違った情報を見せることになる。
#pragma once
#include <QString>

namespace ofd {

// aim を単位ベクトルへ解く。成功したら out[0..2] に x,y,z を入れて true。
// 零ベクトル (長さ 0) は向きとして意味を持たないので false。
bool parseAim(const QString &aim, double out[3]);

} // namespace ofd
