// ── 日本のオペラ対応ホール (opera-halls-data.js, 2026年7月時点) ─────────────
struct OperaHall {
    const char *id;
    const char *region;
    const char *name;
    const char *type;
    int    opened;
    bool   closed;          // status == "closed"
    const char *closure;    // 休館情報 ("" = 開館中)
    int    seats;
    int    volume_m3;
    const char *pitType;
    const char *pitCapacity;
    bool   pitSplit;
    const char *stage;
    double RT_occupied;     // [s]
    bool   rtMeasured;      // true=実測 / false=推定
    double EDT;             // [s]
    double C80;             // [dB]
    double G;               // [dB]
    int    ITDG;            // [ms]
    const char *note;
};

