// ── 世界のコンサートホール (room-acoustics.jsx HALLS) ──────────────────────
struct ConcertHall {
    const char *id;
    const char *name;      // UTF-8
    const char *type;      // ホール型式
    double V;              // 室容積 [m³]
    int    N;              // 席数
    double S_aud;          // 客席面積 [m²]
    double RT;             // RT60 満席 [s]
    double EDT;            // [s]
    double C80;            // [dB]
    double G;              // strength [dB]
    int    ITDG;           // [ms]
    double BQI;            // 1-IACC(E3)
    const char *dims;
    const char *note;
};

