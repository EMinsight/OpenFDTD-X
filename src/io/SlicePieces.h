// SlicePieces.h — 直交する複数断面を「互いの交線」で小片に切り分ける (計算側)。
//
// 3D シーンに断面を 2 枚以上重ねるときに要る。描画側は返ってきた小片を
// 奥から順に塗るだけにする (io/MeshProjection・io/VoxelSlice と同じ分け方 —
// 描画に幾何を書かない)。
//
// ── なぜ切る必要があるのか ────────────────────────────────────────────────
// 隠面消去は「奥から順に塗る」(画家のアルゴリズム) で行っている。ところが
// **直交する 2 枚の面は互いに貫通する**ので、四角形のままでは
// 「どちらが手前か」が面全体では決まらない。どう並べ替えても、貫通した
// 向こう側が手前に出る領域が必ず残る。
//
// 面 A を面 B の位置で切ると、切ったあとの小片は B の片側だけに居るので
// 貫通が無くなり、小片の重心の奥行きで前後が厳密に決まる。直交 3 面なら
// 各面が 4 分割されて計 12 片になる。
//
// ── 面内 2 軸の規約 ──────────────────────────────────────────────────────
// u / v がどの軸かは io/H5Reader::seriesSliceAxes が唯一の出所
// (u は axis = 0 のとき y、他は x。v は axis = 2 のとき y、他は z)。
// ここでもそれを borrow して二重管理にしない。
#pragma once
#include <QVector>

namespace ofd {

// 切り分ける対象の断面 1 枚 (面内の広がりは u/v の範囲で与える)
struct SlicePlane {
    int    axis = 2;                          // 0=X 一定 / 1=Y 一定 / 2=Z 一定
    double pos = 0.0;                         // 固定軸の座標
    double u0 = 0.0, u1 = 0.0;                // 面内 第1軸の範囲
    double v0 = 0.0, v1 = 0.0;                // 面内 第2軸の範囲
};

// 切り分けた小片。plane は入力配列の添字
struct SlicePiece {
    int    plane = 0;
    double ua = 0.0, ub = 0.0;                // ua < ub
    double va = 0.0, vb = 0.0;                // va < vb
};

// 各面を「他の面の固定軸位置」で切り分ける。切る位置がその面の範囲の
// **内側にあるときだけ**切る (端で切っても片方が空になるだけ)。
// 並べ替えはしない — 奥行きは視点に依るので呼び出し側の仕事。
// 面が 1 枚だけなら切らずにそのまま 1 片で返す。
QVector<SlicePiece> cutSlices(const QVector<SlicePlane> &planes);

} // namespace ofd
